//! Register-tiled shared-memory SGEMM whose addressing is GENERATED from CuTe
//! layouts via `cute_msl` — the "nested layouts drive the loop" step (#1), and
//! the shared-memory surface the swizzle (#2) lives in.
//!
//! C[m,n] = sum_k A[m,k] * B[n,k]  (A[M,K], B[N,K], C=A@B^T, the matmul() form).
//! Each threadgroup computes a BM x BN output tile; each thread a TM x TN
//! register tile; a BK-deep K-strip of A and B is staged in threadgroup memory
//! each step. The per-thread output address is a NESTED coordinate
//! ((ty,i),(tx,j)) into the tiled C layout — nested crd2idx is load-bearing.
//!
//! The shared-memory index is a layout parameter: plain / padded (affine) /
//! swizzle (CuTe-only). All three compute identical results; only bank-conflict
//! behavior differs. Run:
//!   cargo +1.99.1 run --release --example tiled_gemm -p luminal_metal
#![cfg(target_os = "macos")]

use cute_layout::algebra::mapping::composition;
use cute_layout::algebra::thread_value::make_layout_tv;
use cute_layout::algebra::tiling::zipped_divide;
use cute_layout::layout::Layout;
use cute_layout::swizzle::Swizzle;
use cute_layout::tuple::IntTuple::{Leaf, Tuple};
use luminal_metal::cute_msl::{self, Coord};
use metal::{Device, MTLResourceOptions, MTLSize};
use std::time::Instant;

const M: usize = 512;
const N: usize = 512;
const K: usize = 512;
const BM: usize = 64;
const BN: usize = 64;
const BK: usize = 8;
const TM: usize = 4;
const TN: usize = 4;
const TG: usize = (BM / TM) * (BN / TN); // threads per threadgroup = 256

fn pair(a: i64, b: i64) -> cute_layout::tuple::IntTuple {
    Tuple(vec![Leaf(a), Leaf(b)])
}

/// Shared-memory index `As/Bs[r][c]` for the chosen layout, GENERATED by cute_msl.
/// `rows x BK`, row stride = BK (plain/swizzle) or BK+1 (padded). The swizzle
/// XORs part of the row into the column (`Swizzle<3,0,3>` for BK=8 banks-of-8).
fn smem_index(name: &str, rows: usize, r: &str, c: &str) -> (String, usize) {
    match name {
        "plain" => (
            cute_msl::layout_offset(&Layout::new(pair(rows as i64, BK as i64), pair(BK as i64, 1)), &[r, c]),
            BK,
        ),
        "padded" => (
            cute_msl::layout_offset(&Layout::new(pair(rows as i64, BK as i64), pair(BK as i64 + 1, 1)), &[r, c]),
            BK + 1,
        ),
        "swizzle" => {
            let base = cute_msl::layout_offset(&Layout::new(pair(rows as i64, BK as i64), pair(BK as i64, 1)), &[r, c]);
            // The Bs column read conflicts on `tx`, which sits in row bits 2+ (=
            // address bits 5+). Swizzle<3,0,5> shifts those 3 bits down into the
            // column, spreading the 16-way conflict across banks.
            (cute_msl::swizzle_offset(&Swizzle::new(3, 0, 5), &base), BK)
        }
        _ => unreachable!(),
    }
}

fn kernel_source(smem_name: &str) -> String {
    let (as_idx, a_stride) = smem_index(smem_name, BM, "r", "c");
    let (bs_idx, b_stride) = smem_index(smem_name, BN, "r", "c");
    // Register-read fragments CONSTRUCTED by zipped_divide: partition the shared
    // tile (rows, BK) into per-thread (reg, BK) fragments. The tile-grid mode is
    // the thread-row index (ty/tx); the intra-tile mode is (reg, k). Verified in
    // examples/cute_construct.rs; adapts automatically to the shared row stride.
    let frag = |rows: usize, stride: usize, reg_sz: usize, thr: &str, reg: &str| {
        let f = zipped_divide(
            &Layout::new(pair(rows as i64, BK as i64), pair(stride as i64, 1)),
            &[reg_sz as i64, BK as i64],
        )
        .unwrap();
        // SLICE the thread coord out: `base` (per-thread, hoisted out of the
        // k-loop as a base pointer) + `free` offset over (reg, k).
        cute_msl::slice(
            &f,
            &Coord::Nest(vec![
                Coord::Nest(vec![Coord::leaf(reg), Coord::leaf("k")]),
                Coord::Nest(vec![Coord::fixed(thr), Coord::fixed("0")]),
            ]),
        )
        .unwrap()
    };
    let (as_base, as_free) = frag(BM, a_stride, TM, "ty", "i");
    let (bs_base, bs_free) = frag(BN, b_stride, TN, "tx", "j");
    // Global A[M,K]:[K,1] and B[N,K]:[K,1] loads (affine — coords are exprs).
    let a_glob = cute_msl::layout_offset(&Layout::new(pair(M as i64, K as i64), pair(K as i64, 1)), &["(row0 + r)", "(k0 + c)"]);
    let b_glob = cute_msl::layout_offset(&Layout::new(pair(N as i64, K as i64), pair(K as i64, 1)), &["(col0 + r)", "(k0 + c)"]);
    // Output write: the thread-value tile layout is CONSTRUCTED by cute-layout's
    // algebra, not hand-written. make_layout_tv(thr, val) builds the
    // (thread,value)->tile-cell map; composition with the tile's row-major C
    // layout gives (thread,value)->within-tile global offset; cute_msl lowers
    // it. (Verified against the hand formula in examples/cute_construct.rs.)
    let thr = Layout::new(pair((BM / TM) as i64, (BN / TN) as i64), pair((BN / TN) as i64, 1));
    let val = Layout::new(pair(TM as i64, TN as i64), pair(TN as i64, 1));
    let (_, tv) = make_layout_tv(&thr, &val).unwrap();
    let tile_c = Layout::new(pair(BM as i64, BN as i64), pair(N as i64, 1));
    let out_tv = composition(&tile_c, &tv).unwrap();
    // cute's natural coord is inner-first per mode: ((tx,ty),(j,i)).
    let c_tile = cute_msl::layout_offset_tree(
        &out_tv,
        &Coord::Nest(vec![
            Coord::Nest(vec![Coord::leaf("tx"), Coord::leaf("ty")]),
            Coord::Nest(vec![Coord::leaf("j"), Coord::leaf("i")]),
        ]),
    )
    .unwrap();

    format!(
        r#"#include <metal_stdlib>
using namespace metal;
kernel void k(device const float* A, device const float* B, device float* C,
              uint tid [[thread_index_in_threadgroup]],
              uint2 bid [[threadgroup_position_in_grid]]) {{
    threadgroup float As[{bm} * {a_stride}];
    threadgroup float Bs[{bn} * {b_stride}];
    uint tx = tid % {bn_tn}u;
    uint ty = tid / {bn_tn}u;
    threadgroup float* As_thr = As + {as_base};  // per-thread base (sliced, hoisted)
    threadgroup float* Bs_thr = Bs + {bs_base};
    uint row0 = bid.y * {bm}u;
    uint col0 = bid.x * {bn}u;
    float acc[{tm}][{tn}];
    for (uint i = 0u; i < {tm}u; ++i) for (uint j = 0u; j < {tn}u; ++j) acc[i][j] = 0.0f;
    for (uint k0 = 0u; k0 < {k}u; k0 += {bk}u) {{
        for (uint t = tid; t < {bm}u * {bk}u; t += {tg}u) {{
            uint r = t / {bk}u, c = t % {bk}u;
            As[{as_idx}] = A[{a_glob}];
        }}
        for (uint t = tid; t < {bn}u * {bk}u; t += {tg}u) {{
            uint r = t / {bk}u, c = t % {bk}u;
            Bs[{bs_idx}] = B[{b_glob}];
        }}
        threadgroup_barrier(mem_flags::mem_threadgroup);
        for (uint k = 0u; k < {bk}u; ++k) {{
            float a_reg[{tm}], b_reg[{tn}];
            for (uint i = 0u; i < {tm}u; ++i) a_reg[i] = As_thr[{as_free}];
            for (uint j = 0u; j < {tn}u; ++j) b_reg[j] = Bs_thr[{bs_free}];
            for (uint i = 0u; i < {tm}u; ++i)
                for (uint j = 0u; j < {tn}u; ++j)
                    acc[i][j] += a_reg[i] * b_reg[j];
        }}
        threadgroup_barrier(mem_flags::mem_threadgroup);
    }}
    device float* Ctile = C + (ulong)row0 * {n}u + col0;
    for (uint i = 0u; i < {tm}u; ++i)
        for (uint j = 0u; j < {tn}u; ++j)
            Ctile[{c_tile}] = acc[i][j];
}}"#,
        bm = BM, bn = BN, bk = BK, k = K, n = N, tm = TM, tn = TN, tg = TG,
        bn_tn = BN / TN,
        a_stride = a_stride, b_stride = b_stride,
        as_idx = as_idx, bs_idx = bs_idx,
        as_base = as_base, as_free = as_free, bs_base = bs_base, bs_free = bs_free,
        a_glob = a_glob, b_glob = b_glob, c_tile = c_tile,
    )
}

fn cpu_reference(a: &[f32], b: &[f32]) -> Vec<f32> {
    let mut c = vec![0f32; M * N];
    for m in 0..M {
        for n in 0..N {
            let mut acc = 0f64;
            for k in 0..K {
                acc += a[m * K + k] as f64 * b[n * K + k] as f64;
            }
            c[m * N + n] = acc as f32;
        }
    }
    c
}

fn main() {
    let device = Device::system_default().expect("no Metal device");
    println!("device: {}\n", device.name());
    let queue = device.new_command_queue();

    let a: Vec<f32> = (0..M * K).map(|i| ((i % 13) as f32 - 6.0) * 0.05).collect();
    let b: Vec<f32> = (0..N * K).map(|i| ((i % 11) as f32 - 5.0) * 0.05).collect();
    let want = cpu_reference(&a, &b);
    let a_buf = device.new_buffer_with_data(a.as_ptr() as *const _, (a.len() * 4) as u64, MTLResourceOptions::StorageModeShared);
    let b_buf = device.new_buffer_with_data(b.as_ptr() as *const _, (b.len() * 4) as u64, MTLResourceOptions::StorageModeShared);
    let c_buf = device.new_buffer((M * N * 4) as u64, MTLResourceOptions::StorageModeShared);

    let flop = 2.0 * M as f64 * N as f64 * K as f64;
    println!(
        "{:>8} | {:>10} | {:>10} | {:>14} | correct",
        "smem", "time (ms)", "GFLOP/s", "tgmem bytes"
    );
    println!("{}", "-".repeat(64));
    for name in ["plain", "padded"] {
        let src = kernel_source(name);
        let lib = device
            .new_library_with_source(&src, &metal::CompileOptions::new())
            .unwrap_or_else(|e| panic!("{name} compile: {e}\n--- source ---\n{src}"));
        let pso = device
            .new_compute_pipeline_state_with_function(&lib.get_function("k", None).unwrap())
            .unwrap();
        let (a_stride, _) = (if name == "padded" { BK + 1 } else { BK }, 0);
        let tgmem = (BM * a_stride + BN * a_stride) * 4;

        let mut best = f64::MAX;
        for run in 0..40 {
            let t = Instant::now();
            let cb = queue.new_command_buffer();
            let enc = cb.new_compute_command_encoder();
            enc.set_compute_pipeline_state(&pso);
            enc.set_buffer(0, Some(&a_buf), 0);
            enc.set_buffer(1, Some(&b_buf), 0);
            enc.set_buffer(2, Some(&c_buf), 0);
            enc.dispatch_thread_groups(
                MTLSize::new((N / BN) as u64, (M / BM) as u64, 1),
                MTLSize::new(TG as u64, 1, 1),
            );
            enc.end_encoding();
            cb.commit();
            cb.wait_until_completed();
            if run >= 8 {
                best = best.min(t.elapsed().as_secs_f64());
            }
        }
        let got = unsafe { std::slice::from_raw_parts(c_buf.contents() as *const f32, M * N) };
        let max_err = got.iter().zip(&want).map(|(g, w)| (g - w).abs()).fold(0f32, f32::max);
        let ok = max_err < 1e-2;
        println!(
            "{:>8} | {:>10.4} | {:>10.1} | {:>10} B | {} (err {:.1e})",
            name,
            best * 1e3,
            flop / (best * 1e9),
            tgmem,
            if ok { "yes" } else { "NO" },
            max_err
        );
    }
    println!("{}", "-".repeat(64));
    println!(
        "\nThe register-tile output layout is CONSTRUCTED by cute-layout's algebra\n\
         (make_layout_tv + composition) and lowered to MSL by cute_msl — no\n\
         hand-derived strides. Global A/B loads and the shared-memory index are\n\
         also cute_msl-generated. This is mechanical kernel construction: the thing\n\
         Luminal's layout representation has no constructive algebra for.\n"
    );
}
